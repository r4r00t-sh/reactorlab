#!/usr/bin/env python3
"""Apply OpenMC collapse JSON → YAML + generated C++ .inc (no invented σ)."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
JSON_PATH = ROOT / "data" / "thorium" / "openmc_collapse" / "ahwr_edu_cell_onegroup.json"
YAML_PATH = ROOT / "data" / "thorium" / "ahwr_edu_chain_v1.yaml"
INC_PATH = ROOT / "core" / "include" / "reactorlab" / "fuelcycle" / "ahwr_collapsed_xs.inc"

KEYS = [
    ("Th232_capture_b", "REACTORLAB_XS_Th232_c"),
    ("Pa233_capture_b", "REACTORLAB_XS_Pa233_c"),
    ("U233_fission_b", "REACTORLAB_XS_U233_f"),
    ("U233_capture_b", "REACTORLAB_XS_U233_c"),
    ("U235_fission_b", "REACTORLAB_XS_U235_f"),
    ("U235_capture_b", "REACTORLAB_XS_U235_c"),
    ("Pu239_fission_b", "REACTORLAB_XS_Pu239_f"),
    ("Pu239_capture_b", "REACTORLAB_XS_Pu239_c"),
]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", type=Path, default=JSON_PATH)
    args = ap.parse_args()
    if not args.json.is_file():
        print(f"missing {args.json}", file=sys.stderr)
        return 1
    data = json.loads(args.json.read_text(encoding="utf-8"))
    sig = data["sigma_b"]
    for key, _macro in KEYS:
        if key not in sig or not isinstance(sig[key], (int, float)) or not (sig[key] > 0.0):
            print(f"bad/missing {key}={sig.get(key)!r}", file=sys.stderr)
            return 1

    text = YAML_PATH.read_text(encoding="utf-8")
    text = text.replace("has_placeholders: true", "has_placeholders: false")
    text = re.sub(
        r"(?m)^  # --- PLACEHOLDER one-group.*\n(?:  #.*\n)*",
        "  # --- OpenMC-collapsed one-group microscopic cross sections [barn] ---\n"
        "  # Source: data/thorium/openmc_collapse/ahwr_edu_cell_onegroup.json (ENDF/B-VIII.0)\n",
        text,
        count=1,
    )
    for key, _macro in KEYS:
        text = re.sub(rf"(?m)^  {key}:.*$", f"  {key}: {sig[key]:.6g}", text, count=1)
    text = text.replace("PLACEHOLDER ", "")
    YAML_PATH.write_text(text, encoding="utf-8")

    lines = [
        "// Generated by scripts/openmc/apply_collapse_to_tree.py — do not edit by hand.",
        "// Values are OpenMC spectrum-averaged barns from ENDF/B-VIII.0 AHWR-edu cell.",
    ]
    for key, macro in KEYS:
        lines.append(f"#define {macro} {sig[key]:.8g}")
    INC_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Updated {YAML_PATH}")
    print(f"Updated {INC_PATH}")
    for key, _ in KEYS:
        print(f"  {key} = {sig[key]:.6g} b")
    return 0


if __name__ == "__main__":
    sys.exit(main())
